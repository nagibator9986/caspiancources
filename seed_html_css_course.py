def _add_questions_to_test(test, questions_data):
    """Добавляет все вопросы из списка в указанный тест."""
    for idx, q_data in enumerate(questions_data, start=1):
        q = Question(
            test_id=test.id,
            text=q_data["text"],
            type=q_data.get("type", "single"),
            order_index=idx,
            points=1,
        )
        db.session.add(q)
        db.session.flush()
        for text, correct in q_data["options"]:
            db.session.add(
                AnswerOption(question_id=q.id, text=text, is_correct=correct)
            )


def create_module_test(module, title, description, questions_data):
    """Создаёт тест по модулю с явно заданными уникальными вопросами."""
    test = Test(
        module_id=module.id,
        type="module",
        title=title,
        description=description,
        pass_score_percent=70,
        max_attempts=None,
    )
    db.session.add(test)
    db.session.flush()

    _add_questions_to_test(test, questions_data)
    print(f"Создан тест по модулю '{module.title}' — {len(questions_data)} уникальных вопросов")
    return test


