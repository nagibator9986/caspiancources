def _wipe_existing_tests_for_course(course):
    """
    Удаляет ТОЛЬКО тесты курса (со всеми вопросами и попытками).
    Уроки, модули, прогресс пользователей и сертификаты НЕ затрагиваются.
    """
    from app.models import UserTestAttempt
    module_ids = [m.id for m in CourseModule.query.filter_by(course_id=course.id).all()]
    tests = (
        Test.query
        .filter((Test.course_id == course.id) | (Test.module_id.in_(module_ids)))
        .all()
    )
    if not tests:
        return 0
    for t in tests:
        UserTestAttempt.query.filter_by(test_id=t.id).delete(synchronize_session=False)
        db.session.delete(t)
    db.session.commit()
    return len(tests)


