def create_module_test(module, title, description, topics_prefix, num_questions=50):
    """
    Создаём тест по модулю с заданным количеством вопросов.
    Часть вопросов явно прописаны, остальные генерируются шаблонно.
    """
    test = Test(
        module_id=module.id,
        type="module",
        title=title,
        description=description,
        pass_score_percent=70,
        max_attempts=None,
    )
    db.session.add(test)
    db.session.flush()

    questions = []

    # Несколько "ручных" осмысленных вопросов
    base_questions = [
        {
            "text": f"{topics_prefix} Что такое искусственный интеллект в контексте данного курса?",
            "options": [
                ("Это любая компьютерная программа", False),
                ("Это система, способная выполнять задачи, требующие человеческого интеллекта", True),
                ("Это только программы для распознавания лиц", False),
                ("Это исключительно опасная технология, запрещённая повсюду", False),
            ],
        },
        {
            "text": f"{topics_prefix} Какое правило безопасности при работе с ИИ является корректным?",
            "options": [
                ("Можно вводить любые личные данные, если сервис известный", False),
                ("Нельзя вводить пароли, номера карт и персональные данные", True),
                ("Всегда доверять любым ответам ИИ без проверки", False),
                ("Запрещено вообще использовать ИИ", False),
            ],
        },
        {
            "text": f"{topics_prefix} Что такое промпт (prompt)?",
            "options": [
                ("Название любой программы на компьютере", False),
                ("Запрос или инструкция, которую мы формулируем для ИИ", True),
                ("Случайный ответ чат-бота", False),
                ("Название раздела в браузере", False),
            ],
        },
    ]

    order_index = 1
    for q_data in base_questions:
        q = Question(
            test_id=test.id,
            text=q_data["text"],
            type="single",
            order_index=order_index,
            points=1,
        )
        db.session.add(q)
        db.session.flush()
        order_index += 1

        for text, correct in q_data["options"]:
            ans = AnswerOption(
                question_id=q.id,
                text=text,
                is_correct=correct,
            )
            db.session.add(ans)

        questions.append(q)

    # Генерация оставшихся вопросов шаблонно
    while len(questions) < num_questions:
        idx = len(questions) + 1
        q = Question(
            test_id=test.id,
            text=f"{topics_prefix} Контрольный вопрос №{idx}: выберите верное утверждение про ИИ.",
            type="single",
            order_index=order_index,
            points=1,
        )
        db.session.add(q)
        db.session.flush()
        order_index += 1
        questions.append(q)

        # Варианты ответов (один правильный)
        opt_list = [
            ("ИИ можно использовать как инструмент для обучения и работы, но результаты нужно проверять", True),
            ("Результаты ИИ всегда абсолютно точны и не требуют проверки", False),
            ("Использовать ИИ можно только для развлечений", False),
            ("Любой текст или картинку из ИИ можно выдавать за свою работу без указания источника", False),
        ]
        for text, correct in opt_list:
            ans = AnswerOption(
                question_id=q.id,
                text=text,
                is_correct=correct,
            )
            db.session.add(ans)

    print(f"Создан тест по модулю '{module.title}' на {len(questions)} вопросов")
    return test


